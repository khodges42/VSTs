"""Package local preview builds and complete corresponding sources; never publish."""
from pathlib import Path
import hashlib
import json
import shutil
import zipfile

project = Path(__file__).resolve().parents[1]
repo = project.parents[1]
build = repo / "target/soundgyal-cmake"
release = repo / "target/releases/soundgyal99-0.3"
release.mkdir(parents=True, exist_ok=True)
bundle = build / "Soundgyal99_artefacts/Release/VST3/SOUNDGYAL 99.vst3"
dependency = repo / "target/soundgyal-deps/JUCE"
if not bundle.is_dir() or not dependency.is_dir():
    raise SystemExit("Build and validate before packaging")

# Captures are actual native/editor images generated by the test executables.
for name in ("soundgyal-vst3.png", "soundgyal-synthesis.png", "soundgyal-matrix.png"):
    shutil.copy2(build / "validation" / name, project / "docs/images" / name)

sources = [
    f for f in project.rglob("*")
    if f.is_file() and not {"third_party", "build", "__pycache__"}.intersection(f.relative_to(project).parts)
]
with zipfile.ZipFile(release / "SOUNDGYAL99-0.3-Windows-x64.zip", "w", zipfile.ZIP_DEFLATED) as archive:
    for f in bundle.rglob("*"):
        if f.is_file():
            archive.write(f, "SOUNDGYAL 99.vst3/" + f.relative_to(bundle).as_posix())
    for f in sources:
        rel = f.relative_to(project)
        if rel.parts[0] in {"docs", "factory", "notices"} or rel.name in {"README.md", "LICENSE", "NOTICE", "UPSTREAM.md"}:
            archive.write(f, rel.as_posix())

dependency_files = [f for f in dependency.rglob("*") if f.is_file() and ".git" not in f.relative_to(dependency).parts]
manifest = {f.relative_to(dependency).as_posix(): hashlib.sha256(f.read_bytes()).hexdigest() for f in dependency_files}
with zipfile.ZipFile(release / "SOUNDGYAL99-0.3-complete-source.zip", "w", zipfile.ZIP_DEFLATED) as archive:
    for f in sources:
        archive.write(f, "plugins/soundgyal99/" + f.relative_to(project).as_posix())
    prefix = "target/soundgyal-deps/JUCE/"
    for f in dependency_files:
        archive.write(f, prefix + f.relative_to(dependency).as_posix())
    archive.writestr(prefix + "SOURCE_REVISION", "4f43011b96eb0636104cb3e433894cda98243626\n")
    archive.writestr(prefix + "SOURCE_SHA256.json", json.dumps(manifest, indent=2) + "\n")

new_presets = [
    "Dred Reverse Bass", "FM Donk", "Liquid Glass Keys", "Formant Roller",
    "Classic Wobble", "Riddim Square", "Vowel Growl", "Metallic Yoi",
    "Deep Dub Pluck", "Rave Fifth Stab",
]
with zipfile.ZipFile(release / "SOUNDGYAL99-0.3-preset-auditions.zip", "w", zipfile.ZIP_DEFLATED) as archive:
    for name in new_presets:
        for suffix in (".wav", "-held.wav"):
            archive.write(build / "validation" / (name + suffix), name + suffix)
    for name in ("Jungle Hoover.wav", "Hoover-before-note60.wav", "Hoover-after-note60.wav"):
        archive.write(build / "validation" / name, name)
    archive.write(project / "docs/presets-0.3.md", "Audition-notes.md")

hashes = {f.name: hashlib.sha256(f.read_bytes()).hexdigest() for f in release.glob("*.zip")}
(release / "SHA256.json").write_text(json.dumps(hashes, indent=2) + "\n")
print(release)
